"""Alembic environment: runs migrations through the app's async engine against `Base.metadata`.

Serves: D-012 (schema-first migrations), D-001 (SQLAlchemy 2 async).
Callers: the `alembic` CLI (configured by apps/api/alembic.ini). Every `modules/*/models.py` is imported
below so autogenerate and `alembic check` see all tables.
"""

import asyncio
import importlib
import importlib.util
import pkgutil

from alembic import context
from geoalchemy2 import alembic_helpers
from sqlalchemy.engine import Connection

import agritrace.modules
from agritrace.core.config import get_settings
from agritrace.core.db import Base, get_engine

# core may not import modules (D-004), so the migration environment loads every module's tables itself.
for _module in pkgutil.iter_modules(agritrace.modules.__path__):
    if importlib.util.find_spec(f"agritrace.modules.{_module.name}.models"):
        importlib.import_module(f"agritrace.modules.{_module.name}.models")

target_metadata = Base.metadata
# GeoAlchemy2's hooks skip PostGIS internal tables (spatial_ref_sys) and render geometry columns and
# spatial indexes correctly in autogenerated migrations.
GEO_HOOKS = {
    "include_object": alembic_helpers.include_object,
    "process_revision_directives": alembic_helpers.writer,
    "render_item": alembic_helpers.render_item,
}


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of executing it (`alembic upgrade head --sql`).

    Side effects:
        Writes the migration SQL to standard output.
    """
    context.configure(
        url=get_settings().database_url, target_metadata=target_metadata, literal_binds=True, **GEO_HOOKS
    )
    with context.begin_transaction():
        context.run_migrations()


def _run_sync(connection: Connection) -> None:
    """Run the migrations on a sync connection handed over by the async engine.

    Args:
        connection: the sync facade of an async connection.

    Side effects:
        Alters the database schema and the `alembic_version` table.
    """
    # The postgis image puts tiger/topology on the search path; their tables are not ours to diff.
    connection.exec_driver_sql("SET search_path TO public")
    context.configure(connection=connection, target_metadata=target_metadata, **GEO_HOOKS)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    """Connect with the app's async engine and run the migrations.

    Raises:
        sqlalchemy.exc.SQLAlchemyError: the database is unreachable or a migration fails.

    Side effects:
        Alters the database schema; disposes the engine afterwards.
    """
    engine = get_engine()
    async with engine.connect() as connection:
        await connection.run_sync(_run_sync)
        await connection.commit()
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
