/**
 * Generates `src/api/generated/error-messages.ts` (error code -> user message) from the table in
 * `docs/api/error-codes.md`, so the portal never hard-codes API error texts.
 * Serves: docs/api/conventions.md "Error envelope" (apps show their own text for `code`), plan §7.3 P00.
 * Called by: `npm run gen:api` (and therefore `npm run gen:check` in CI). Run with plain `node` (type stripping).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const SOURCE = resolve(import.meta.dirname, '../../../docs/api/error-codes.md');
const TARGET = resolve(import.meta.dirname, '../src/api/generated/error-messages.ts');

/** One row of the error-code table. */
export interface ErrorCodeRow {
  /** Registered snake_case code, e.g. `validation_error`. */
  code: string;
  /** The "Meaning" column, shown to the user. */
  message: string;
}

/**
 * Extracts `code` and "Meaning" from every data row of the markdown table in error-codes.md.
 * @param markdown Full text of docs/api/error-codes.md.
 * @returns The rows in document order.
 * @throws {Error} When no row is found or the header no longer has the `Code` and `Meaning` columns,
 *   so a format change in the generated markdown fails CI instead of emptying the table.
 */
export function parseErrorTable(markdown: string): ErrorCodeRow[] {
  const lines = markdown.split('\n').filter((line) => line.trim().startsWith('|'));
  const header = (lines[0] ?? '').split('|').map((cell) => cell.trim());
  const codeCol = header.indexOf('Code');
  const meaningCol = header.indexOf('Meaning');
  if (codeCol < 0 || meaningCol < 0) {
    throw new Error('error-codes.md: table header must have "Code" and "Meaning" columns');
  }
  const rows = lines.slice(2).map((line) => {
    const cells = line.split('|').map((cell) => cell.trim());
    return {
      code: (cells[codeCol] ?? '').replaceAll('`', ''),
      message: cells[meaningCol] ?? '',
    };
  });
  if (rows.length === 0 || rows.some((row) => !/^[a-z][a-z0-9_]*$/.test(row.code))) {
    throw new Error('error-codes.md: no rows, or a row without a snake_case code');
  }
  return rows;
}

/**
 * Renders the TypeScript module written to src/api/generated/error-messages.ts.
 * @param rows Parsed table rows.
 * @returns The module source text.
 */
export function renderModule(rows: ErrorCodeRow[]): string {
  const entries = rows.map((row) => `  ${row.code}: ${JSON.stringify(row.message)},`).join('\n');
  return `/**
 * GENERATED by apps/portal/scripts/gen-error-messages.ts from docs/api/error-codes.md. NEVER EDIT BY HAND:
 * run \`npm run gen:api\`. Maps every registered API error \`code\` to the English message shown to users.
 * Serves: docs/api/conventions.md "Error envelope". Called by: src/api/errors.ts.
 */
export const ERROR_MESSAGES: Readonly<Record<string, string>> = {
${entries}
};
`;
}

if (import.meta.main) {
  writeFileSync(TARGET, renderModule(parseErrorTable(readFileSync(SOURCE, 'utf8'))));
}
